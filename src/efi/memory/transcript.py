"""
efi/memory/transcript.py

Превращение `Session` в плоский текст переписки для тех запросов, где диалог
подаётся модели ОДНИМ куском текста, а не структурой ролей: новеллизация
эпизода в дневник (efi/memory/consolidation.py) и восприятие фактов
(efi/memory/parser.py).

Зачем отдельный модуль. В обычном запросе к чат-модели роли (`user` /
`assistant`) — часть протокола: модель не может перепутать, чья реплика чья,
потому что они лежат в разных полях. Как только диалог схлопывается в текст,
эта гарантия исчезает и остаётся только то, что написано в самих строках.

А написано там было вот что:

    user: Рома: привет, как оно
    assistant: да норм, я тут весь вечер с плёнкой вожусь

Дальше модель просят: «запиши это в дневник от первого лица». Ей нужно
сообразить, что английское служебное слово `assistant` в русском тексте
означает «я», а `user` — «не я», и не перепутать направление. На модели
бесплатного тира этого не происходит стабильно, и в дневник регулярно
попадало «Рома весь вечер возился с плёнкой» — с точностью до наоборот. Хуже
того, промпт новеллизации прямо обещал, что «перед каждой репликой указано
имя написавшего», а renderer подставлял туда `user`/`assistant`: обещание не
выполнялось, и модель добирала недостающее догадкой.

Отсюда правило: в плоском тексте реплики Эфи помечаются её собственным
именем и явной пометкой «это ты», а чужие — именем написавшего, которое уже
приходит в самом тексте сообщения (см. efi.telegram.formatting.
format_user_message). Ролевых слов протокола в тексте не остаётся вовсе.
"""

from __future__ import annotations

import re

from efi.llm.schemas import Role, Session

#: Пометка при репликах самой Эфи. Именно словами, а не «assistant:» —
#: это ровно то место, где терялось направление разговора.
SELF_MARKER = "это ты"

#: Как называется собеседник, если имени в тексте реплики не оказалось.
#: Такое бывает у старых записей истории, сохранённых до появления
#: format_user_message, и у сообщений из источников без отправителя.
_UNKNOWN_SPEAKER = "собеседник"

#: Подпись отправителя, которую format_user_message ставит в начало текста.
#: Ровно две формы: «Рома: привет» и «Рома (в ответ на: "..."): привет».
#: Проверка нужна, чтобы не написать «собеседник: Рома: привет» — двойная
#: подпись читается как два разных участника.
#:
#: Имя ограничено и по длине, и по составу: без второго условия обычная
#: фраза с двоеточием («слушай, я тут подумал вот о чём и решил написать:
#: давай перенесём») сходила бы за подпись, и «именем» становилась половина
#: предложения. Запятых и точек в отображаемых именах не бывает, а в такой
#: фразе они есть почти всегда.
_NAME_PREFIX_RE = re.compile(r"^[^\n:(,.!?;]{1,64}(?:\s\([^\n]*?\))?:\s")

#: Строка-легенда в начале текста. Дублирует то, что и так написано в каждой
#: строке, — намеренно: на длинной переписке модель опирается на начало
#: текста, а на короткой хватило бы и одних пометок.
_LEGEND = (
    "Ниже переписка. Реплики с пометкой «({marker})» — ТВОИ СОБСТВЕННЫЕ слова, "
    "все остальные написали другие люди, их имена стоят в начале строки."
)

_OMITTED_HEAD_NOTICE = "[...начало разговора опущено...]"


def render_transcript(session: Session, *, self_name: str, char_limit: int) -> str:
    """
    Плоский текст переписки с однозначной атрибуцией реплик.

    Пустой результат означает, что в сессии не было ни одной содержательной
    реплики (голые tool-calls в дневник не идут).

    При переполнении `char_limit` обрезается НАЧАЛО, а не конец: свежая часть
    разговора ещё ни разу не осмыслена, а начало, скорее всего, уже попало в
    дневник прошлым проходом. Легенда при этом остаётся на месте — она нужна
    именно тогда, когда текста много.
    """
    lines = [
        _render_line(message.role, message.content, self_name=self_name)
        for message in session
        if message.content.strip()
    ]
    if not lines:
        return ""

    body = "\n".join(lines)
    legend = _LEGEND.format(marker=SELF_MARKER)
    if len(body) > char_limit:
        body = f"{_OMITTED_HEAD_NOTICE}\n{body[-char_limit:]}"
    return f"{legend}\n\n{body}"


def _render_line(role: Role, content: str, *, self_name: str) -> str:
    text = content.strip()
    if role is Role.ASSISTANT:
        return f"{self_name} ({SELF_MARKER}): {text}"
    if _NAME_PREFIX_RE.match(text):
        # Имя уже подписано в самом тексте (format_user_message) — второй раз
        # подписывать нельзя.
        return text
    return f"{_UNKNOWN_SPEAKER}: {text}"


__all__ = ["SELF_MARKER", "render_transcript"]
