"""
efi/behavior/energy.py

Энергия и самочувствие Эфи как ПРОЦЕСС, а не как поле, которое кто-то
когда-нибудь заполнит.

Что было не так. `WorkingMemorySnapshot.energy` менялся ровно одним способом:
модель должна была сама, по своей воле, вызвать инструмент `update_self_state`
и сказать «я устала». Инструмент есть, описание у него честное («не на каждую
реплику, а когда это правда важно»), и именно поэтому он не вызывался
практически никогда — у модели нет причины тратить ход на служебное действие,
которого от неё никто не ждал в этой реплике. В результате энергия стояла на
дефолтных 0.7 месяцами, а `emotional_state`/`physical_state` оставались
пустыми строками, и в промпт с дашбордом уходило «не записано».

Это не мелочь в отображении. Энергия — вход для efi.behavior.busy_engine
(усталая Эфи отвечает медленнее), и константа там означает, что целая
подсистема поведения работает вхолостую. А «состояние: не определено» в
промпте — прямая подсказка модели, что состояния у неё и нет.

Как устроено теперь. У живого существа энергия не ждёт решения — она сама
падает к ночи, восстанавливается за сон и тратится на разговоры. Здесь ровно
это:

    energy(now) = релаксация от последнего известного значения
                  к циркадной норме текущего часа

Никакого фонового цикла: значение вычисляется в момент, когда его спросили,
из сохранённого якоря (уровень + время) и прошедшего времени. Разговор
списывает немного энергии и переставляет якорь — то есть усталость копится
именно от общения, а не от того, что процесс запущен.

Явное `update_self_state` при этом никуда не делось и остаётся сильнее всего
остального: если Эфи сказала «я вымотана», это ставит якорь на её значение, а
дальше он так же естественно релаксирует. Модель по-прежнему может назвать
своё состояние словами — просто теперь её молчание не означает, что состояния
нет.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timedelta

#: Циркадная норма: к какому уровню энергия стремится в этот час суток.
#: Границы те же, что у частей суток в промпте (efi/prompts/builder.py), чтобы
#: «глубокая ночь» в тексте и провал энергии совпадали, а не разъезжались.
#:
#: Значения подобраны по человеческой норме, а не по красоте кривой: провал
#: под утро глубже вечернего (в 4 утра тяжелее, чем в 23), после обеда —
#: заметная, но небольшая просадка, пик — в первой половине дня.
_CIRCADIAN: tuple[tuple[int, int, float], ...] = (
    (0, 5, 0.20),    # глубокая ночь — она должна хотеть спать
    (5, 7, 0.35),    # только продрала глаза
    (7, 9, 0.60),    # раннее утро — уже расходится
    (9, 12, 0.85),   # утро — пик
    (12, 15, 0.80),
    (15, 17, 0.65),  # послеобеденная просадка
    (17, 22, 0.75),  # вечер — второе дыхание
    (22, 24, 0.40),  # ночь — уже клонит
)

#: За сколько времени энергия проходит примерно две трети пути до нормы.
#: Полтора часа — компромисс: за короткий перерыв в разговоре Эфи не
#: «отсыпается» до пика, но и не таскает вчерашнюю усталость в сегодняшний
#: день.
_RELAXATION = timedelta(hours=1.5)

#: Сколько энергии стоит один ход разговора.
#:
#: Значение подобрано на симуляции реального ритма переписки, а не на глаз:
#: полчаса вечернего трёпа (реплика в две минуты) стоит около восьми пунктов,
#: два часа подряд — около двадцати, а неспешный час днём почти не заметен,
#: потому что восстановление успевает отыграть большую часть. При 0.02, с
#: которых начиналось, тот же двухчасовой вечер сажал энергию до девяти
#: процентов — то есть один разговор выматывал Эфи сильнее, чем целые сутки.
TURN_COST = 0.006

#: Ниже этого — она откровенно вымотана; выше — на подъёме. Пороги нужны для
#: словесного описания состояния, а не для арифметики.
_EXHAUSTED_BELOW = 0.3
_TIRED_BELOW = 0.5
_LIVELY_ABOVE = 0.75


def circadian_baseline(hour: int) -> float:
    """Норма энергии для этого часа суток."""
    for start, end, level in _CIRCADIAN:
        if start <= hour < end:
            return level
    return 0.7


@dataclass(slots=True, frozen=True)
class EnergyState:
    """
    Энергия на конкретный момент плюс то, как она читается словами.

    Словесная часть здесь, а не в промпт-билдере, потому что описание должно
    совпадать с числом по построению: «бодрая» при 0.2 — это ровно тот сорт
    расхождения, из-за которого потом не понять, чему верить.
    """

    level: float
    label: str
    #: Клонит в сон: либо энергия на нуле, либо просто глухая ночь.
    is_sleepy: bool

    @property
    def percent(self) -> int:
        return round(self.level * 100)


def project(
    *,
    anchor: float,
    anchor_at: datetime | None,
    now: datetime,
) -> EnergyState:
    """
    Энергия на момент `now`, исходя из последнего известного значения.

    `anchor_at is None` — снимок из версии до появления этой модели, где в
    поле лежит ровно то самое зависшее навсегда дефолтное значение. Такой
    якорь считается бесконечно старым, то есть энергия сразу равна норме
    своего часа. Обратное решение («якорь свежий») законсервировало бы
    починенный баг: файл рабочей памяти пережил бы обновление и продолжил
    показывать те же 70% в любое время суток.
    """
    baseline = circadian_baseline(now.hour)
    if anchor_at is None:
        level = baseline
    else:
        level = _relax(anchor, baseline, elapsed=now - anchor_at)
    return EnergyState(level=level, label=describe(level, now.hour), is_sleepy=_is_sleepy(level, now.hour))


def spend(anchor: float, *, turns: int = 1) -> float:
    """Списывает стоимость `turns` ходов разговора, не уводя энергию ниже нуля."""
    return _clamp(anchor - TURN_COST * max(0, turns))


def describe(level: float, hour: int) -> str:
    """
    Состояние словами — то, что видит и модель в промпте, и человек на
    дашборде.

    Час нужен не для красоты: 0.35 в девять вечера — это «выдохлась за день»,
    а в четыре утра — «нормально для такого времени». Одно и то же число
    означает разное.
    """
    if level < _EXHAUSTED_BELOW:
        return "почти без сил, вырубает" if _is_night(hour) else "выжата, еле шевелится"
    if level < _TIRED_BELOW:
        return "клонит в сон" if _is_night(hour) else "подсевшая, на автопилоте"
    if level > _LIVELY_ABOVE:
        return "на подъёме, бодрая"
    return "спокойная, в норме"


def _is_sleepy(level: float, hour: int) -> bool:
    return level < _TIRED_BELOW or _is_night(hour)


def _is_night(hour: int) -> bool:
    return hour >= 23 or hour < 6


def _relax(current: float, target: float, *, elapsed: timedelta) -> float:
    """
    Экспоненциальное приближение к норме: быстро в начале, медленно у цели.

    Линейное приближение здесь выглядело бы одинаково на графике, но вело бы
    себя неверно на краях — доезжало бы до нормы ровно и застревало на ней,
    тогда как усталость как раз и ощущается тем, что последние проценты
    возвращаются дольше всего.
    """
    seconds = max(0.0, elapsed.total_seconds())
    if seconds <= 0.0:
        return _clamp(current)
    ratio = 1.0 - 0.5 ** (seconds / _RELAXATION.total_seconds() * 1.5)
    return _clamp(current + (target - current) * ratio)


def _clamp(value: float) -> float:
    return max(0.0, min(value, 1.0))


__all__ = ["TURN_COST", "EnergyState", "circadian_baseline", "describe", "project", "spend"]
