"""
efi/llm/timeouts.py

Сколько ждать ответа: столько, сколько разумно ждать ИМЕННО ЭТОТ ответ.

Один таймаут на эндпоинт — это ошибка, которая долго выглядит как настройка.
`timeout_seconds = 15` в конфиге разумен для реплики в чат: человек ждёт, и
через пятнадцать секунд молчания разговор уже сломан. Но тот же эндпоинт
вечером пишет дневник на четыре тысячи токенов, и пятнадцати секунд ему не
хватит НИКОГДА — ни на быстрой модели, ни на медленной. В логе это выглядит
как «request timed out after 15.0s» подряд у всех кандидатов роли, а в жизни
— как оборванные дневники и «не смогла ответить» вместо ответа.

Отсюда правило: бюджет складывается из времени на «подумать» (константа
эндпоинта) и времени на «написать» — пропорционально тому, сколько текста
попросили. Тысяча токенов на самохостируемой модели это десятки секунд, и
знать об этом должен код, а не владелец, который иначе вынужден держать один
компромиссный таймаут на все задачи сразу.

Потолки разные, потому что цена ожидания разная. В чате ждёт живой человек:
там лучше поздний ответ, чем никакого, но не «через пять минут». В фоне не
ждёт никто, и единственная разумная граница — не держать задачу вечно.
"""

from __future__ import annotations

#: Сколько секунд закладывать на каждую тысячу токенов вывода. Ориентир —
#: медленная самохостируемая модель (десятки токенов в секунду); на быстром
#: облаке запас просто не понадобится, потому что ответ придёт раньше.
SECONDS_PER_1K_TOKENS = 40.0

#: Потолок для диалога: дольше ждать бессмысленно — разговор уже сломан.
INTERACTIVE_CEILING_SECONDS = 90.0

#: Потолок для фоновых задач (дневник, спека, анализ кода). Здесь никто не
#: ждёт, и единственное, чего нельзя, — держать задачу бесконечно.
BACKGROUND_CEILING_SECONDS = 300.0


def request_timeout(
    base_seconds: float,
    *,
    max_output_tokens: int,
    interactive: bool,
    seconds_per_1k: float = SECONDS_PER_1K_TOKENS,
) -> float:
    """
    Бюджет одного запроса: база эндпоинта плюс время на запрошенный объём.

    Никогда не меньше базы: настройка владельца — это нижняя граница, а не
    единственное значение. Никогда не больше потолка своей роли: неограниченный
    таймаут превращает один медленный ответ в зависшую задачу.
    """
    ceiling = INTERACTIVE_CEILING_SECONDS if interactive else BACKGROUND_CEILING_SECONDS
    generation = max(0, max_output_tokens) / 1000.0 * seconds_per_1k
    return min(max(base_seconds, base_seconds + generation), max(ceiling, base_seconds))


__all__ = [
    "BACKGROUND_CEILING_SECONDS",
    "INTERACTIVE_CEILING_SECONDS",
    "SECONDS_PER_1K_TOKENS",
    "request_timeout",
]
