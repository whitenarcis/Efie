"""
efi/utils/text.py

Работа с текстом, оборванным на полуслове.

Зачем. Ответ модели, упёршийся в лимит токенов, ничем не отличается от
обычного — он просто заканчивается посреди фразы. Если такой текст сохранить
в дневник как есть, получается запись вида «...хотя ещё лет пять назад это»:
формально запись, фактически обрубок, и отличить её от настоящей потом
невозможно — ни человеку, ни RAG-поиску, который будет подмешивать этот
обрубок в промпт как воспоминание.

Кириллица делает проблему заметно чаще, чем кажется по числам лимитов: у
большинства токенизаторов бесплатных моделей русский текст стоит в 2-3 раза
дороже английского того же смысла, поэтому бюджет, подобранный «на глаз» по
английским примерам, режет русскую запись на середине.

Отсюда правило: оборванный хвост отрезается по последней ЗАКОНЧЕННОЙ фразе,
а если законченных фраз в тексте не оказалось — запись не сохраняется вовсе.
Половина мысли хуже, чем её отсутствие: отсутствие видно, а обрубок
притворяется целым.
"""

from __future__ import annotations

import re

#: Границы предложения. Многоточие и закрывающие кавычки/скобки учитываются
#: явно: «...это правда." » должно считаться законченным, а не обрезаться
#: перед кавычкой.
_SENTENCE_END_RE = re.compile(r'[.!?…](?:["»)\]]|\s|$)')

#: Насколько мало может остаться от текста после отрезания хвоста, чтобы
#: результат ещё считался осмысленным. Если модель успела написать одно
#: короткое предложение и оборвалась на середине второго — первое сохранить
#: стоит; если от абзаца уцелело меньше трети, это уже не запись, а огрызок.
_MIN_KEPT_RATIO = 0.3

#: Абсолютный минимум длины: короче этого текст не несёт содержания, каким бы
#: ни было соотношение.
_MIN_KEPT_CHARS = 40


def trim_to_last_sentence(text: str, *, min_chars: int = _MIN_KEPT_CHARS, min_ratio: float = _MIN_KEPT_RATIO) -> str:
    """
    Отрезает оборванный хвост по последней законченной фразе.

    Возвращает пустую строку, если спасать нечего: законченных предложений
    нет вовсе, либо от текста осталось слишком мало. Пустой результат —
    осмысленный ответ, а не ошибка: вызывающая сторона по нему понимает, что
    запись создавать не нужно.

    Чистая функция без состояния — поведение целиком проверяется тестами.
    """
    stripped = (text or "").strip()
    if not stripped:
        return ""

    last_end = -1
    for match in _SENTENCE_END_RE.finditer(stripped):
        # Конец найденной границы: сам знак плюс закрывающая кавычка/скобка,
        # если она есть. Пробел в конец не включаем — его снимет strip().
        last_end = match.start() + 1
        tail = match.group()[1:]
        if tail and not tail.isspace():
            last_end += len(tail)

    if last_end <= 0:
        return ""

    kept = stripped[:last_end].strip()
    if len(kept) < min_chars or len(kept) < len(stripped) * min_ratio:
        return ""
    return kept


def salvage_truncated(text: str, *, truncated: bool) -> str:
    """
    Текст, который допустимо сохранить, с учётом отчёта провайдера об обрыве.

    `truncated` — это `Response.was_truncated`, то есть finish_reason вида
    "length". Если провайдер сказал «закончил сам», текст берётся как есть:
    не дело эвристики решать, что автор обязан ставить точку в конце.

    Если провайдер сказал «оборвал по лимиту», текст всё равно сначала
    проверяется на вид: лимит иногда совпадает с концом фразы, и тогда резать
    нечего. И только если хвост действительно висит на полуслове — он
    отрезается по последней законченной фразе (возможно, до пустой строки).
    """
    cleaned = (text or "").strip()
    if not cleaned:
        return ""
    if truncated and looks_unfinished(cleaned):
        return trim_to_last_sentence(cleaned)
    return cleaned


def looks_unfinished(text: str) -> bool:
    """
    Похож ли текст на оборванный — по последнему символу.

    Нужен там, где `finish_reason` от провайдера недоступен или соврал (у
    бесплатных прокси это не редкость). Не заменяет проверку finish_reason, а
    дополняет её: тут возможны ложные срабатывания на записях, которые автор
    и правда закончил без точки, поэтому эвристика применяется только как
    вторая линия, когда провайдер уже сказал «оборвано».
    """
    stripped = (text or "").rstrip()
    if not stripped:
        return True
    return stripped[-1] not in '.!?…"»)]:;'


__all__ = ["looks_unfinished", "salvage_truncated", "trim_to_last_sentence"]
