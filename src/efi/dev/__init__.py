"""
efi/dev/

Цифровое ремесло Эфи: от замысла проекта до запушенного репозитория.

Подсистема собрана из пяти частей, каждая из которых умеет ровно одно:

    schemas.py      — что такое проект: спецификация, файл, задача, статус.
    qwen_client.py  — руки: Qwen Coder через Groq пишет и правит код файлов.
    sandbox.py      — совесть: сгенерированный код проверяется, НЕ запускаясь.
    engine.py       — голова: спека главной моделью, затем цикл «написать —
                      проверить — починить» по каждому файлу.
    github_sync.py  — публикация: репозиторий, осмысленные коммиты, пуш.
    reporter.py     — голос: поводы рассказать о процессе в чате.
    store.py        — память: задачи переживают перезапуск.
    worker.py       — фоновый цикл, который всё это связывает.

Главный принцип, из-за которого части разделены именно так: генерация кода —
это не «спросить у модели», а конвейер с проверкой на каждом шаге. Одна
модель придумывает, что делать (утилитарное, а не «Hello World»), другая
пишет код, песочница ловит синтаксис и линт, и только прошедшее проверку
уходит в git. Ни на одном шаге сгенерированный код не ИСПОЛНЯЕТСЯ — см.
докстринг efi/dev/sandbox.py, это осознанная граница, а не недоработка.
"""

