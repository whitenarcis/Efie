"""
efi/dev/showcase.py

Когда уместно упомянуть свою наработку — и когда это уже реклама.

Модуль отвечает на один вопрос: есть ли среди выложенных проектов Эфи
такой, который ПО СУЩЕСТВУ относится к тому, что сейчас обсуждают. Нужен он
внешнему флексу (efi/prompts/builder.py): в чужом канале, где зашёл разговор
про разбор логов, сослаться на свою утилиту для разбора логов — нормальное
человеческое поведение, а вставить ту же ссылку в разговор про кофе —
спам, за который выгоняют из сообщества.

Совпадение считается по словам САМОГО ПРОЕКТА (доля его значимых слов,
встретившихся в тексте), а общие технические слова из счёта исключены:
«python» и «код» есть в половине постов любого айтишного канала, и по ним
любой проект «подходил бы» всегда.

Отдельный модуль, а не функция в билдере промпта: это правило про её
проекты, а не про сборку промпта, — и проверяется оно отдельно, без
промптов вообще.
"""

from __future__ import annotations

import re

from efi.dev.schemas import DevTask

#: Доля значимых слов проекта, которая должна встретиться в тексте, чтобы
#: упоминание считалось уместным. Половина — это уже не «оба про питон», а
#: «говорят ровно про то, что я написала».
MIN_SHOWCASE_SCORE = 0.5

_TOKEN_RE = re.compile(r"[\w-]+", re.UNICODE)
_MIN_TOKEN_LENGTH = 4

#: Слова сравниваются по началу, а не целиком. Причина — русская морфология:
#: «разбирает логи» в описании проекта и «кто-нибудь разбирал логи» в чужом
#: посте — это одно и то же слово в разных формах, а при точном сравнении
#: они не совпадают вовсе. Полноценная лемматизация потребовала бы словаря
#: и зависимости; пяти букв достаточно, чтобы склеить формы одного слова и
#: при этом не склеить разные («парсер»/«парсинг» — да, «логи»/«логика» —
#: нет).
_STEM_LENGTH = 5

#: Слова, которые есть у каждого второго проекта и в каждом втором посте.
#: Совпадение по ним ничего не значит, поэтому в счёт они не идут.
_STOP_TOKENS = frozenset(
    {
        "python", "питон", "код", "коде", "кода", "кодом", "проект", "проекта", "проекте",
        "утилита", "утилиту", "утилиты", "скрипт", "скрипта", "инструмент", "программа",
        "github", "гитхаб", "версия", "релиз", "https", "http", "разработка", "написал",
        "написала", "сделал", "сделала", "который", "которая", "которые", "чтобы", "можно",
    }
)


def significant_tokens(text: str) -> set[str]:
    """
    Значимые слова текста, усечённые до основы (см. _STEM_LENGTH).

    Публичная: тем же способом efi.dev.engine узнаёт, не придумала ли она
    заново проект, который уже написала. Правило «что считать одной и той же
    темой» должно быть одно на всю подсистему, иначе повтор, который здесь
    считается совпадением, там окажется новой идеей.
    """
    return {
        token.lower()[:_STEM_LENGTH]
        for token in _TOKEN_RE.findall(text or "")
        if len(token) >= _MIN_TOKEN_LENGTH and token.lower() not in _STOP_TOKENS
    }


def showcase_score(text: str, task: DevTask) -> float:
    """
    Насколько текст относится к теме проекта: доля значимых слов проекта,
    встретившихся в тексте. Чистая функция — проверяется без БД и без LLM.
    """
    if task.spec is None or not task.repo_url:
        return 0.0

    subject = f"{task.spec.title} {task.spec.problem}"
    project_tokens = significant_tokens(subject)
    if not project_tokens:
        return 0.0

    text_tokens = significant_tokens(text)
    if not text_tokens:
        return 0.0
    return len(project_tokens & text_tokens) / len(project_tokens)


def pick_showcase(
    text: str, releases: list[DevTask], *, min_score: float = MIN_SHOWCASE_SCORE
) -> DevTask | None:
    """
    Самый подходящий к тексту проект — или None, если ни один не в тему.

    None здесь основной, а не исключительный исход: чаще всего разговор идёт
    не про то, что она писала, и молчание — правильный ответ.
    """
    best: tuple[float, DevTask] | None = None
    for task in releases:
        score = showcase_score(text, task)
        if score >= min_score and (best is None or score > best[0]):
            best = (score, task)
    return best[1] if best is not None else None


__all__ = ["MIN_SHOWCASE_SCORE", "pick_showcase", "showcase_score", "significant_tokens"]
