"""
efi/security/sanitize.py

Санитайзинг произвольного внешнего текста (сообщения собеседников, имена
профилей, описания медиа) перед тем, как он попадёт в промпт LLM. Прямой
аналог llmui/malicious_payloads.h у референса.

Подход — структурный, а не "детектор фраз": вместо попытки распознать
конкретные формулировки вида "игнорируй предыдущие инструкции" (что
тривиально обходится перефразированием и не масштабируется), функция убирает
конкретные технические векторы:
    - невидимые/форматирующие юникод-символы, которыми маскируют инъекции
      (zero-width space/joiner, RTL/LTR-оверрайды и т.п.);
    - последовательности, имитирующие служебные разметочные маркеры нашего
      собственного пайплайна или известных форматов промптов других систем
      (что могло бы запутать модель о том, где заканчивается "чужой текст" и
      начинаются настоящие инструкции) — не удаляются, а размыкаются;
    - юникод-нормализация (NFKC) против гомоглифов;
    - жёсткое ограничение длины (огромный внешний текст — типичный вектор
      DoS/переполнения контекста, не только инъекций).

Санитайзинг снижает техническую площадь атаки, а не "решает" prompt
injection как класс — это не замена здравому смыслу модели и не гарантия.
"""

from __future__ import annotations

import re
import unicodedata

# Невидимые/управляющие символы, которыми на практике маскируют инъекции:
# zero-width space/non-joiner/joiner, BOM, RTL/LTR-оверрайды и метки направления.
_INVISIBLE_CHARS_RE = re.compile(
    "[\u200b\u200c\u200d\u200e\u200f\u202a\u202b\u202c\u202d\u202e\ufeff\u2060-\u2064]"
)

# Последовательности, имитирующие служебные разметочные маркеры (наши или
# известных форматов чужих LLM-пайплайнов). Не удаляются (это могло бы
# выглядеть как цензура и уничтожить легитимный контекст), а размыкаются —
# вставкой zero-width space внутрь маркера, невидимой для человека, но
# разрушающей для токенизатора/модели как структурная последовательность.
_STRUCTURAL_MARKERS_RE = re.compile(
    r"(<\|[^|>]{0,64}\|>|\[/?(?:INST|SYS|SYSTEM)\]|<<SYS>>|<</SYS>>|###\s*(?:SYSTEM|INSTRUCTION)\b)",
    re.IGNORECASE,
)

_DEFAULT_MAX_LENGTH = 4000
_DEFAULT_NAME_MAX_LENGTH = 128
_ZERO_WIDTH_BREAK = "\u200b"


def sanitize_text(text: str, *, max_length: int = _DEFAULT_MAX_LENGTH) -> str:
    """
    Санитайзинг одного текстового поля (сообщение, описание медиа и т.п.)
    перед вставкой в промпт LLM. Идемпотентна: повторный вызов на уже
    очищенном тексте ничего не меняет.
    """
    normalized = unicodedata.normalize("NFKC", text)
    without_invisibles = _INVISIBLE_CHARS_RE.sub("", normalized)
    defused = _STRUCTURAL_MARKERS_RE.sub(_defuse_marker, without_invisibles)
    if len(defused) > max_length:
        defused = defused[:max_length].rstrip() + "…"
    return defused


def sanitize_display_name(name: str, *, max_length: int = _DEFAULT_NAME_MAX_LENGTH) -> str:
    """
    Санитайзинг короткого поля вроде имени/юзернейма — та же обработка, что и
    у sanitize_text, но с более жёстким ограничением длины: легитимные имена
    короткие, а попытка протащить инъекцию через "имя" длиной в тысячи
    символов уже сама по себе подозрительна.
    """
    return sanitize_text(name, max_length=max_length)


def _defuse_marker(match: re.Match[str]) -> str:
    marker = match.group(0)
    if len(marker) <= 1:
        return marker
    # Для человека/логов маркер выглядит так же, но токенизатор уже не
    # увидит оригинальную непрерывную структурную последовательность.
    return marker[0] + _ZERO_WIDTH_BREAK + marker[1:]


__all__ = ["sanitize_text", "sanitize_display_name"]
